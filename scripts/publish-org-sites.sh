#!/usr/bin/env bash
# Publish each org's site (dist/<key>/, written by build.py) to that org's
# <org>.github.io repo. Creates the repo and turns on GitHub Pages the first
# time. Commits only when the built site changed.
#
#   python3 build.py && scripts/publish-org-sites.sh            # all orgs
#   scripts/publish-org-sites.sh ai-workforce                   # one org
#   DRY_RUN=1 scripts/publish-org-sites.sh                      # show, don't push
set -euo pipefail

SITE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST="$SITE/dist"
DRY_RUN="${DRY_RUN:-0}"
ONLY="${1:-}"

log() { printf '[publish] %s\n' "$*"; }
die() { log "ERROR: $*" >&2; exit 1; }

[[ -d "$DIST" ]] || die "no dist/; run python3 build.py first"
command -v gh >/dev/null || die "gh CLI is required"

# key<TAB>org login, from the same data the build used. (A while-read loop,
# not mapfile, so this runs on macOS's bash 3.2.)
ORGS=()
while IFS= read -r row; do ORGS+=("$row"); done < <(python3 -c '
import json, sys
for o in json.load(open(sys.argv[1]))["orgs"]:
    print(o["key"] + "\t" + o["login"])' "$SITE/data/curricula.json")

publish_one() {
  local key="$1" login="$2"
  local owner repo work
  owner="$(printf '%s' "$login" | tr '[:upper:]' '[:lower:]')"
  repo="$owner.github.io"
  [[ -d "$DIST/$key" ]] || die "missing $DIST/$key"

  # A transferred repo leaves a redirect at its old name (the umbrella site
  # used to be ai-infra-curriculum/ai-infra-curriculum.github.io), so check the
  # canonical name: never publish into a repo that merely redirects here.
  local actual
  actual="$(gh api "repos/$owner/$repo" --jq .full_name 2>/dev/null | tr '[:upper:]' '[:lower:]' || true)"
  if [[ "$actual" != "$owner/$repo" ]]; then
    [[ -n "$actual" ]] && log "$owner/$repo: currently redirects to $actual; creating the real repo"
    log "$owner/$repo: creating"
    [[ "$DRY_RUN" == 1 ]] || gh repo create "$owner/$repo" --public \
      --description "Site for the $owner curriculum (generated by ai-curriculum-project.github.io)" >/dev/null
  fi
  [[ "$DRY_RUN" == 1 ]] && { log "$owner/$repo: would publish dist/$key"; return; }

  work="$(mktemp -d)"
  trap 'rm -rf "$work"' RETURN
  if ! git clone -q "https://github.com/$owner/$repo.git" "$work/repo" 2>/dev/null; then
    die "$owner/$repo: clone failed"
  fi
  actual="$(gh api "repos/$owner/$repo" --jq .full_name | tr '[:upper:]' '[:lower:]')"
  [[ "$actual" == "$owner/$repo" ]] || die "$owner/$repo resolves to $actual; refusing to publish"
  (
    cd "$work/repo"
    git checkout -q -B main
    find . -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
    cp -R "$DIST/$key/." .
    cat > README.md <<EOF
# $repo

The site for this curriculum, served at <https://$repo/>.

Generated by [ai-curriculum-project.github.io](https://github.com/ai-curriculum-project/ai-curriculum-project.github.io)
(\`build.py\` + \`scripts/publish-org-sites.sh\`). Don't edit here; changes are overwritten on the next publish.
EOF
    git add -A
    if git diff --cached --quiet; then
      log "$owner/$repo: unchanged"
    else
      git -c user.useConfigOnly=false commit -q -m "site: rebuild from ai-curriculum-project.github.io"
      git push -q origin main
      log "$owner/$repo: published"
    fi
  )
  if ! gh api "repos/$owner/$repo/pages" >/dev/null 2>&1; then
    gh api -X POST "repos/$owner/$repo/pages" -f "source[branch]=main" -f "source[path]=/" >/dev/null \
      && log "$owner/$repo: Pages enabled"
  fi
  log "$owner/$repo: https://$repo/"
}

for row in "${ORGS[@]}"; do
  key="${row%%$'\t'*}"; login="${row#*$'\t'}"
  [[ -z "$ONLY" || "$ONLY" == "$key" ]] || continue
  publish_one "$key" "$login"
done
